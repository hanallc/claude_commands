#!/usr/bin/env -S ${HOME}/.claude/scripts/lib/py
"""Write the Unicode tables that the Rust style reader uses to match the Python token reader.

The Python token reader in style_footprint uses str.isspace, the re classes \\d and \\w, and
str.splitlines. Rust has no exact match for them: char::is_whitespace leaves out U+001C to U+001F.
This script reads each class from this Python and writes it as code-point ranges.

Usage: style_reader_tables.py [--check]
--check exits 1 when the Rust file differs from what this Python writes.
"""

from __future__ import annotations

import argparse
import re
import sys
import unicodedata
from collections.abc import Callable
from pathlib import Path

TABLES_PATH = Path(__file__).resolve().parents[2] / "rust/style_reader/src/unicode_tables.rs"
SURROGATES = range(0xD800, 0xE000)
DECIMAL = re.compile(r"\d")
WORD = re.compile(r"\w")


def _is_line_boundary(character: str) -> bool:
    return len(f"a{character}b".splitlines()) == 2


# Each table: its Rust name, what it holds, and the Python test for one character.
TABLES: tuple[tuple[str, str, Callable[[str], bool]], ...] = (
    ("DECIMAL", "Characters that the Python re class `\\d` matches.", lambda c: DECIMAL.fullmatch(c) is not None),
    ("LINE_BOUNDARIES", "Characters where Python `str.splitlines` ends a line.", _is_line_boundary),
    ("SPACE", "Characters for which Python `str.isspace` is true.", str.isspace),
    ("WORD", "Characters that the Python re class `\\w` matches.", lambda c: WORD.fullmatch(c) is not None),
)


def ranges(test: Callable[[str], bool]) -> list[tuple[int, int]]:
    """Return the inclusive code-point ranges where test is true."""
    result: list[tuple[int, int]] = []
    for code_point in range(sys.maxunicode + 1):
        if code_point in SURROGATES or not test(chr(code_point)):
            continue
        if result and result[-1][1] == code_point - 1:
            result[-1] = (result[-1][0], code_point)
        else:
            result.append((code_point, code_point))
    return result


def rust_source() -> str:
    lines = [
        "//! Unicode classes of the Python token reader, as inclusive code-point ranges.",
        "//!",
        f"//! Generated by `scripts/style/style_reader_tables.py` from Unicode {unicodedata.unidata_version}.",
        "//! Do not edit; run the script again.",
    ]
    for name, description, test in TABLES:
        found = ranges(test)
        lines.append("")
        lines.append(f"/// {description}")
        lines.append(f"pub(crate) const {name}: &[(u32, u32)] = &[")
        lines.extend(f"    (0x{start:04X}, 0x{end:04X})," for start, end in found)
        lines.append("];")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    _ = parser.add_argument("--check", action="store_true", help="exit 1 when the Rust file is not current")
    check = bool(parser.parse_args().check)  # pyright: ignore[reportAny]
    source = rust_source()
    if check:
        current = TABLES_PATH.read_text() if TABLES_PATH.exists() else ""
        if current != source:
            print(f"{TABLES_PATH} is not current; run {Path(__file__).name}", file=sys.stderr)
            return 1
        return 0
    _ = TABLES_PATH.write_text(source)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
