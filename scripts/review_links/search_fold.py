_TRANSLATION = {
    point: chr(point + offset)
    for start, end, step, offset in RANGES
    for point in range(start, end + 1, step)
} | EXCEPTIONS


def fold(text: str) -> str:
    return text.lower() if text.isascii() else text.translate(_TRANSLATION)


def _build_table() -> tuple[tuple[FoldRange, ...], dict[int, str]]:
    """Group single-character mappings with the same step and offset."""
    single: list[tuple[int, int]] = []
    exceptions: dict[int, str] = {}
    for point, character in enumerate(map(chr, range(maxunicode + 1))):
        folded = character.casefold()
        if folded == character:
            continue
        if len(folded) == 1:
            single.append((point, ord(folded) - point))
        else:
            exceptions[point] = folded
    ranges: list[FoldRange] = []
    index = 0
    while index < len(single):
        start, offset = single[index]
        end = index + 1
        step = single[end][0] - start if end < len(single) else 0
        if step in (1, 2):
            while end < len(single) and single[end] == (start + (end - index) * step, offset):
                end += 1
        if end - index >= 3:
            ranges.append((start, single[end - 1][0], step, offset))
            index = end
        else:
            exceptions[start] = chr(start + offset)
            index += 1
    return tuple(ranges), dict(sorted(exceptions.items()))


def regenerate() -> None:
    if unidata_version != UNICODE_VERSION:
        raise SystemExit(f"Use a Python interpreter with Unicode {UNICODE_VERSION}.")
    ranges, exceptions = _build_table()
    ranges_text = "".join(f"    {entry},\n" for entry in ranges)
    exceptions_text = "".join(f"    {point}: {ascii(value)},\n" for point, value in exceptions.items())
    generated = (f"RANGES: tuple[FoldRange, ...] = (\n{ranges_text})\n"
                 + f"EXCEPTIONS: dict[int, str] = {{\n{exceptions_text}}}")
    file = Path(__file__)
    start = "\n# BEGIN GENERATED TABLE\n"
    end = "\n# END GENERATED TABLE\n"
    before, body = file.read_text(encoding="utf-8").split(start, 1)
    _, after = body.split(end, 1)
    _ = file.write_text(before + start + generated + end + after, encoding="utf-8")


if __name__ == "__main__":
    regenerate()
